#PROGRAM TO DEMONSTRATE STRING
s="PYTHON"
print("original string : ",s)

print("\n---string indexing---")
print("char at index 0 : ",s[0])
print("char at index 1 : ",s[1])
print("char at index 2 : ",s[2])
print("char at index 3 : ",s[3])
print("char at index 4 : ",s[4])
print("char at  index5 : ",s[5])

print("\n---string indexing---")
print("first char : ",s[-6])
print("sec last char :  ",s[-2])
print("third last char : ",s[-3])

print("\n---string slicing---")
print("first 3 char : ",s[0:3])
print("char from 2 to 4 : ",s[2:5])
print("firt 4 char : ",s[:4])
print("from index 2 toend : ",s[2:])
print("last 3 char : ",s[-3:])

print("\n reverse string : ",s[::-1])

